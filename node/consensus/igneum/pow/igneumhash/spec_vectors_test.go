// the hash team's vectors (pow/vectors/igneumhash/<variant>/, generated by
// the C reference from SPEC-R0A-v0.md): the G0 agreement for this package's
// WORK, written from the spec's text. Under the fixture rule a missing
// vector tree fails rather than passes.
const specVectorsRoot = "../../../../../pow/vectors/igneumhash"

type specVectorFile struct {
	Params  json.RawMessage `json:"params"`
	Vectors []struct {
		Height json.Number `json:"height"`
		Header string      `json:"header"`
		Nonce  string      `json:"nonce"`
		Mix    string      `json:"mix"`
		Hash   string      `json:"hash"`
	} `json:"vectors"`
}

func loadSpecVectors(t *testing.T, variant, class string) (Params, specVectorFile) {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(specVectorsRoot, variant, class+".json"))
	if err != nil {
		if os.Getenv("IGNEUM_REQUIRE_FIXTURES") != "" {
			t.Fatalf("the hash team's vectors are missing: %v", err)
		}
		t.Skipf("the hash team's vectors are not beside this tree: %v", err)
	}
	var f specVectorFile
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatal(err)
	}
	_, p, err := DecodeChainParams(versionedParams(t, variant, f.Params))
	if err != nil {
		t.Fatalf("%s/%s params: %v", variant, class, err)
	}
	return p, f
}

// versionedParams pins the version of a vector file's params document from
// the variant name when the document omits it: the version 0 directories
// were written when an absent version meant 0 (spec 0.3); under 0.4 it means
// 1, so the document alone would select the wrong algorithm.
func versionedParams(t *testing.T, variant string, doc json.RawMessage) json.RawMessage {
	t.Helper()
	var m map[string]json.RawMessage
	if err := json.Unmarshal(doc, &m); err != nil {
		t.Fatal(err)
	}
	changed := false
	if _, ok := m["version"]; !ok {
		v := "1"
		if !strings.HasPrefix(variant, "v1-") {
			v = "0"
			t.Logf("%s: params document carries no version; version 0 from the variant name", variant)
		}
		m["version"] = json.RawMessage(v)
		changed = true
	}
	// A version 4 file whose params echo omits item_bytes takes the width
	// from the variant tag's -w<W> (the generator's echo of 10 October 2026
	// left it out; the digest P pins it either way).
	if _, ok := m["item_bytes"]; !ok && (strings.HasPrefix(variant, "v4-") || strings.HasPrefix(variant, "v6-")) {
		if i := strings.LastIndex(variant, "-w"); i >= 0 {
			m["item_bytes"] = json.RawMessage(variant[i+2:])
			changed = true
		}
	}
	if changed {
		out, err := json.Marshal(m)
		if err != nil {
			t.Fatal(err)
		}
		return out
	}
	return doc
}

// TestStrataDocuments pins the four frozen width documents to their digests
// (STEP1-NOTES.md section 3): 52 canonical bytes, ITEM_BYTES at byte 48.
func TestStrataDocuments(t *testing.T) {
	want := map[uint32]string{
		64:  "ee50122701d3b2c8bf04113cb3db24e839aae67d",
		128: "69e4a4e7211aac188e589cbdb04d8e6ad5f45c0b059318d88897f3a3dcfc5c72",
		256: "612bf2d834abc7ab34b7a08e86958d0f7f3a215e7c7b95d0f783bd07c7a12f12",
		512: "e10d0be2528542feabd405137cee768051c6535bc6eb19d87db3d486e5134c98",
	}
	for w, digest := range want {
		doc := fmt.Sprintf(`{"version": 4, "dataset_mib": 2048, "scratch_kib": 0, "rounds": 64, "cache_mib": 32, "parents": 256, "item_bytes": %d}`, w)
		_, p, err := DecodeChainParams([]byte(doc))
		if err != nil {
			t.Fatalf("width %d: %v", w, err)
		}
		if p.Size() != 52 || p.ItemWidth() != w || p.Items() != (2048<<20)/uint64(w) {
			t.Fatalf("width %d: size %d width %d items %d", w, p.Size(), p.ItemWidth(), p.Items())
		}
		if got := fmt.Sprintf("%x", p.Hash()); !strings.HasPrefix(got, digest) {
			t.Fatalf("width %d: P %s, the register says %s", w, got, digest)
		}
	}
	v6 := map[string]string{
		`{"version": 6, "dataset_mib": 2048, "scratch_kib": 0, "rounds": 64, "cache_mib": 32, "parents": 256, "item_bytes": 128}`: "18d733c6",
		`{"version": 6, "dataset_mib": 2048, "scratch_kib": 0, "rounds": 64, "cache_mib": 32, "parents": 256, "item_bytes": 256}`: "5caa3f31",
		`{"version": 6, "dataset_mib": 2048, "scratch_kib": 0, "rounds": 32, "cache_mib": 32, "parents": 256, "item_bytes": 256}`: "e962af9d",
		`{"version": 6, "dataset_mib": 2048, "scratch_kib": 0, "rounds": 16, "cache_mib": 32, "parents": 256, "item_bytes": 512}`: "98be5fc9",
		`{"version": 6, "dataset_mib": 4096, "scratch_kib": 0, "rounds": 16, "cache_mib": 32, "parents": 256, "item_bytes": 512}`: "9aed5aec",
		`{"version": 6, "dataset_mib": 2048, "scratch_kib": 0, "rounds": 8, "cache_mib": 32, "parents": 256, "item_bytes": 1024}`: "d828684b",
	}
	for doc, digest := range v6 {
		_, p, err := DecodeChainParams([]byte(doc))
		if err != nil {
			t.Fatal(err)
		}
		if got := fmt.Sprintf("%x", p.Hash()); !strings.HasPrefix(got, digest) {
			t.Fatalf("version 6 %s: P %s, STEP1-NOTES says %s", doc, got, digest)
		}
	}
	for _, bad := range []string{`{"version": 4, "dataset_mib": 2048, "cache_mib": 32, "parents": 256}`, `{"version": 4, "dataset_mib": 2048, "cache_mib": 32, "parents": 256, "item_bytes": 96}`, `{"version": 1, "item_bytes": 128}`, `{"version": 4, "dataset_mib": 2048, "cache_mib": 32, "parents": 256, "item_bytes": 256, "scratch_kib": 16}`} {
		if _, _, err := DecodeChainParams([]byte(bad)); err == nil {
			t.Fatalf("accepted: %s", bad)
		}
	}
}

// TestSpecTraceWide walks the reference's version 4 trace vectors through
// MixWide's round record (the item index, the item word h, the item's words
// as read, the registers after the exchange) at every width, and names the
// first round and field that disagree.
func TestSpecTraceWide(t *testing.T) {
	for _, variant := range []string{"v4-d2048-s0-r64-k32-p256-w64", "v4-d2048-s0-r64-k32-p256-w128", "v4-d2048-s0-r64-k32-p256-w256", "v4-d2048-s0-r64-k32-p256-w512", "v4-d4096-s0-r64-k32-p256-w128", "v4-d4096-s0-r64-k32-p256-w256", "v4-d2048-s0-r32-k32-p256-w256", "v4-d2048-s0-r16-k32-p256-w512", "v4-d2048-s0-r8-k32-p256-w1024", "v4-d4096-s0-r16-k32-p256-w512", "v6-d2048-s0-r64-k32-p256-w128", "v6-d2048-s0-r64-k32-p256-w256", "v6-d2048-s0-r32-k32-p256-w256", "v6-d2048-s0-r16-k32-p256-w512", "v6-d4096-s0-r16-k32-p256-w512", "v6-d2048-s0-r8-k32-p256-w1024"} {
		t.Run(variant, func(t *testing.T) {
			raw, err := os.ReadFile(filepath.Join(specVectorsRoot, variant, "trace.json"))
			if err != nil {
				if os.Getenv("IGNEUM_REQUIRE_FIXTURES") != "" {
					t.Fatal(err)
				}
				t.Skip(err)
			}
			var f struct {
				Params  json.RawMessage `json:"params"`
				Vectors []struct {
					Height json.Number `json:"height"`
					Header string      `json:"header"`
					Nonce  string      `json:"nonce"`
					Mix    string      `json:"mix"`
					Trace  struct {
						Init   [8][laneWords]uint32 `json:"init"`
						Rounds []struct {
							R    uint32               `json:"r"`
							Idx  uint32               `json:"idx"`
							H    uint32               `json:"h"`
							Item []uint32             `json:"item"`
							Regs [8][laneWords]uint32 `json:"regs"`
						} `json:"rounds"`
					} `json:"trace"`
				} `json:"vectors"`
			}
			if err := json.Unmarshal(raw, &f); err != nil {
				t.Fatal(err)
			}
			_, p, err := DecodeChainParams(versionedParams(t, variant, f.Params))
			if err != nil {
				t.Fatal(err)
			}
			for vi, v := range f.Vectors {
				height, _ := strconv.ParseUint(v.Height.String(), 10, 64)
				nonce, _ := strconv.ParseUint(v.Nonce, 10, 64)
				want := v.Trace
				var failed string
				w := specWork{
					trace: func(stage string, round uint32, idx uint32, R *[8][laneWords]uint32, fold *[8][4]uint32) {
						if stage == "init" && failed == "" && *R != want.Init {
							failed = "after 4.1 (lane init)"
						}
					},
					traceWide: func(round uint32, idx uint32, h uint32, item []uint32, R *[8][laneWords]uint32) {
						if failed != "" || int(round) >= len(want.Rounds) {
							return
						}
						wr := want.Rounds[round]
						switch {
						case idx != wr.Idx:
							failed = fmt.Sprintf("round %d: item index %d, the reference says %d", round, idx, wr.Idx)
						case len(item) != len(wr.Item):
							failed = fmt.Sprintf("round %d: %d item words, the reference says %d", round, len(item), len(wr.Item))
						case h != wr.H:
							failed = fmt.Sprintf("round %d: item word %d, the reference says %d (first words %v against %v)", round, h, wr.H, item[:4], wr.Item[:4])
						case *R != wr.Regs:
							failed = fmt.Sprintf("round %d: registers differ (lane 0 %v, the reference says %v)", round, R[0][:4], wr.Regs[0][:4])
						default:
							for k := range item {
								if item[k] != wr.Item[k] {
									failed = fmt.Sprintf("round %d: item word %d is %d, the reference says %d", round, k, item[k], wr.Item[k])
									break
								}
							}
						}
					},
				}
				a := New(DefaultChainID, p, w)
				mix, _ := a.Compute(common.HexToHash(v.Header), height, nonce)
				if failed != "" {
					t.Fatalf("trace %d: %s", vi, failed)
				}
				if mix != common.HexToHash(v.Mix) {
					t.Fatalf("trace %d: mix %x, the reference says %s", vi, mix[:], v.Mix)
				}
			}
		})
	}
}

