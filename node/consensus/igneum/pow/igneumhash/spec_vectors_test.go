func testSpecTrace(t *testing.T, variant string) {
	raw, err := os.ReadFile(filepath.Join(specVectorsRoot, variant, "trace.json"))
	if err != nil {
		if os.Getenv("IGNEUM_REQUIRE_FIXTURES") != "" {
			t.Fatal(err)
		}
		t.Skip(err)
	}
	var f struct {
		Params  json.RawMessage `json:"params"`
		Vectors []struct {
			Height json.Number     `json:"height"`
			Header string          `json:"header"`
			Nonce  string          `json:"nonce"`
			Trace  json.RawMessage `json:"trace"`
		} `json:"vectors"`
	}
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatal(err)
	}
	_, p, err := DecodeChainParams(versionedParams(t, variant, f.Params))
	if err != nil {
		t.Fatal(err)
	}
	env := NewEnvelope(DefaultChainID, p)
	t.Logf("params %+v P %x", p, env.P)
	for i, v := range f.Vectors {
		var tr map[string]json.RawMessage
		if err := json.Unmarshal(v.Trace, &tr); err != nil {
			t.Fatal(err)
		}
		height, _ := strconv.ParseUint(v.Height.String(), 10, 64)
		nonce, _ := strconv.ParseUint(v.Nonce, 10, 64)
		var want string
		if err := json.Unmarshal(tr["S"], &want); err == nil {
			if got := env.Seed(common.HexToHash(v.Header), nonce); fmt.Sprintf("%x", got) != want {
				t.Fatalf("trace %d: S %x, the reference says %s", i, got, want)
			}
		}
		if err := json.Unmarshal(tr["E"], &want); err == nil {
			if got := env.EpochSeed(env.Epoch(height)); fmt.Sprintf("%x", got) != want {
				t.Fatalf("trace %d: E %x, the reference says %s", i, got, want)
			}
		}
		if err := json.Unmarshal(tr["P"], &want); err == nil {
			if got := env.P; fmt.Sprintf("%x", got) != want {
				t.Fatalf("trace %d: P %x, the reference says %s", i, got, want)
			}
		}
	}
}

// TestSpecTraceRegisters walks the reference's trace vectors through WORK's
// intermediates (the registers after 4.1 and 4.2, each round's item index
// and registers, the fold), for the version 1 baseline and a version 0
// variant with a scratchpad, and names the first stage that disagrees.
func TestSpecTraceRegisters(t *testing.T) {
	for _, variant := range []string{"v1-d1024-s0-r64-k32-p256", "d256-s16-r64-c1"} {
		t.Run(variant, func(t *testing.T) {
			raw, err := os.ReadFile(filepath.Join(specVectorsRoot, variant, "trace.json"))
			if err != nil {
				if os.Getenv("IGNEUM_REQUIRE_FIXTURES") != "" {
					t.Fatal(err)
				}
				t.Skip(err)
			}
			var f struct {
				Params  json.RawMessage `json:"params"`
				Vectors []struct {
					Height json.Number `json:"height"`
					Header string      `json:"header"`
					Nonce  string      `json:"nonce"`
					Trace  struct {
						Init   [8][laneWords]uint32 `json:"init"`
						Fill   [8][laneWords]uint32 `json:"fill"`
						Rounds []struct {
							R    uint32               `json:"r"`
							Idx  uint32               `json:"idx"`
							Regs [8][laneWords]uint32 `json:"regs"`
						} `json:"rounds"`
						Fold [8][4]uint32 `json:"fold"`
					} `json:"trace"`
				} `json:"vectors"`
			}
			if err := json.Unmarshal(raw, &f); err != nil {
				t.Fatal(err)
			}
			_, p, err := DecodeChainParams(versionedParams(t, variant, f.Params))
			if err != nil {
				t.Fatal(err)
			}
			for vi, v := range f.Vectors {
				height, _ := strconv.ParseUint(v.Height.String(), 10, 64)
				nonce, _ := strconv.ParseUint(v.Nonce, 10, 64)
				want := v.Trace
				var failed string
				w := specWork{trace: func(stage string, round uint32, idx uint32, R *[8][laneWords]uint32, fold *[8][4]uint32) {
					if failed != "" {
						return
					}
					switch stage {
					case "init":
						if *R != want.Init {
							failed = fmt.Sprintf("after 4.1 (lane init): lane 0 %v, the reference says %v", R[0][:4], want.Init[0][:4])
						}
					case "fill":
						if p.ScratchBytes > 0 && *R != want.Fill {
							failed = fmt.Sprintf("after 4.2 (scratch fill): lane 0 %v, the reference says %v", R[0][:4], want.Fill[0][:4])
						}
					case "round":
						if int(round) >= len(want.Rounds) {
							return
						}
						wr := want.Rounds[round]
						if idx != wr.Idx {
							failed = fmt.Sprintf("round %d: item index %d, the reference says %d", round, idx, wr.Idx)
						} else if *R != wr.Regs {
							failed = fmt.Sprintf("round %d: registers differ (lane 0 %v, the reference says %v)", round, R[0][:4], wr.Regs[0][:4])
						}
					case "fold":
						if *fold != want.Fold {
							failed = fmt.Sprintf("fold: %v, the reference says %v", fold[0], want.Fold[0])
						}
					}
				}}
				a := New(DefaultChainID, p, w)
				a.Compute(common.HexToHash(v.Header), height, nonce)
				if failed != "" {
					t.Fatalf("trace %d: %s", vi, failed)
				}
			}
		})
	}
}

// TestSpecMalformed runs the reference's verify-reason class (malformed.json)
// through the adapter: "ok" verifies, "boundary" is the result above the
// target, "mix" the mix digest first even when the boundary is wrong too,
// and "epoch" and "height" are proofs whose claimed height is not the chain
// context's, which the engine refuses before the algorithm runs (the
// adapter is given the validated height only); here the claimed height's
// epoch is shown to change the mix.
func TestSpecMalformed(t *testing.T) {
	for _, variant := range []string{"v1-d1024-s0-r64-k32-p256", "d256-s16-r64-c1"} {
		t.Run(variant, func(t *testing.T) {
			raw, err := os.ReadFile(filepath.Join(specVectorsRoot, variant, "malformed.json"))
			if err != nil {
				if os.Getenv("IGNEUM_REQUIRE_FIXTURES") != "" {
					t.Fatal(err)
				}
				t.Skip(err)
			}
			var f struct {
				Params  json.RawMessage `json:"params"`
				Vectors []struct {
					Height    json.Number `json:"height"`
					Header    string      `json:"header"`
					Nonce     string      `json:"nonce"`
					CtxHeight json.Number `json:"ctx_height"`
					Mix       string      `json:"mix"`
					Boundary  string      `json:"boundary"`
					Expect    string      `json:"expect"`
				} `json:"vectors"`
			}
			if err := json.Unmarshal(raw, &f); err != nil {
				t.Fatal(err)
			}
			_, p, err := DecodeChainParams(versionedParams(t, variant, f.Params))
			if err != nil {
				t.Fatal(err)
			}
			a := New(DefaultChainID, p, defaultWork())
			for i, v := range f.Vectors {
				height, _ := strconv.ParseUint(v.Height.String(), 10, 64)
				ctx, _ := strconv.ParseUint(v.CtxHeight.String(), 10, 64)
				nonce, _ := strconv.ParseUint(v.Nonce, 10, 64)
				header, mix := common.HexToHash(v.Header), common.HexToHash(v.Mix)
				target := new(big.Int).SetBytes(common.FromHex(v.Boundary))
				switch v.Expect {
				case "ok", "boundary", "mix":
					if height != ctx {
						t.Fatalf("vector %d: %s with height %d and context %d", i, v.Expect, height, ctx)
					}
					err := pow.VerifyTarget(a, header, ctx, nonce, mix, target)
					want := map[string]error{"ok": nil, "boundary": pow.ErrResultAboveTarget, "mix": pow.ErrInvalidMixDigest}[v.Expect]
					if !errors.Is(err, want) && !(want == nil && err == nil) {
						t.Fatalf("vector %d (%s): %v, want %v", i, v.Expect, err, want)
					}
				case "epoch", "height":
					if height == ctx {
						t.Fatalf("vector %d: %s with height equal to the context", i, v.Expect)
					}
					// The engine refuses a header whose Number is not the chain
					// context's height before the algorithm runs (consensus.go,
					// verifySeal). At the claimed height the mix would differ
					// unless the epoch is the same.
					if got, _ := a.Compute(header, height, nonce); a.Epoch(height) != a.Epoch(ctx) && got == mix {
						t.Fatalf("vector %d (%s): the mix at height %d equals the context's", i, v.Expect, height)
					}
				default:
					t.Fatalf("vector %d: unknown expectation %q", i, v.Expect)
				}
			}
			t.Logf("%d malformed vectors agree", len(f.Vectors))
		})
	}
}
