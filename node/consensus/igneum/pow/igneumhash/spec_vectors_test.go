func TestSpecVectors(t *testing.T) {
	for name, work := range Works {
		if _, wide := work.(interface {
			MixWide(seed, epochSeed [32]byte, item WideItemFunc, p Params) [32]byte
		}); !wide {
			t.Logf("%s: no whole-item round; the version 4 sets run on the spec work only", name)
		}
		for _, variant := range specVariants {
			if _, wide := work.(interface {
				MixWide(seed, epochSeed [32]byte, item WideItemFunc, p Params) [32]byte
			}); !wide && (strings.HasPrefix(variant, "v4-") || strings.HasPrefix(variant, "v6-")) {
				continue
			}
			for _, class := range []string{"unseen", "transitions", "nonce-boundary"} {
				t.Run(name+"/"+variant+"/"+class, func(t *testing.T) {
					p, f := loadSpecVectors(t, variant, class)
					a := New(DefaultChainID, p, work)
					testSpecVectorFile(t, a, f)
				})
			}
		}
	}
}

func testSpecVectorFile(t *testing.T, a *Algorithm, f specVectorFile) {
	t.Helper()
	if len(f.Vectors) == 0 {
		t.Fatal("no vectors")
	}
	for i, v := range f.Vectors {
		height, err := strconv.ParseUint(v.Height.String(), 10, 64)
		if err != nil {
			t.Fatal(err)
		}
		nonce, err := strconv.ParseUint(v.Nonce, 10, 64)
		if err != nil {
			t.Fatal(err)
		}
		mix, hash := a.Compute(common.HexToHash(v.Header), height, nonce)
		if mix != common.HexToHash(v.Mix) || hash != common.HexToHash(v.Hash) {
			t.Fatalf("vector %d (height %d, nonce %d): mix %x hash %x, the reference says %s %s", i, height, nonce, mix, hash, v.Mix, v.Hash)
		}
	}
	t.Logf("%d vectors agree", len(f.Vectors))
}

// TestWorksAgree: the two WORK implementations compute the same M on random
// inputs across the matrix, beyond the published vectors.
func TestWorksAgree(t *testing.T) {
	for _, p := range ablation()[:6] {
		spec := New(DefaultChainID, p, Works["spec"])
		cand := New(DefaultChainID, p, Works["candidate"])
		for i := 0; i < 4; i++ {
			h := common.BytesToHash([]byte{byte(i), byte(p.Rounds), byte(p.Version)})
			m1, f1 := spec.Compute(h, uint64(i)*4096, uint64(i)*0x9E3779B97F4A7C15)
			m2, f2 := cand.Compute(h, uint64(i)*4096, uint64(i)*0x9E3779B97F4A7C15)
			if m1 != m2 || f1 != f2 {
				t.Fatalf("%+v: the two WORK implementations disagree at %d: %x %x vs %x %x", p, i, m1, f1, m2, f2)
			}
		}
	}
	if err := SelectWork("nothing"); err == nil {
		t.Fatal("unknown WORK selected")
	}
	if err := SelectWork("candidate"); err != nil {
		t.Fatal(err)
	}
	if _, ok := defaultWork().(CandidateWork); !ok {
		t.Fatal("the selection did not take")
	}
	if err := SelectWork("spec"); err != nil {
		t.Fatal(err)
	}
}

