#!/usr/bin/env python3
"""tools_embed_kernels.py OUT.cpp FILE...: writes the embedded kernel table (name, body) for kernel_source.cpp."""
import os, sys
out = sys.argv[1]; files = sys.argv[2:]
def lit(s):
    parts = []
    for i in range(0, len(s), 4000):
        chunk = s[i:i + 4000].replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        parts.append('"' + chunk + '"')
    return "\n".join(parts) if parts else '""'
with open(out, "w") as o:
    o.write("// generated by tools_embed_kernels.py; do not edit\nnamespace igm {\n")
    o.write("extern const char *const kEmbeddedKernelNames[];\nextern const char *const kEmbeddedKernelBodies[];\nextern const int kEmbeddedKernelCount;\nconst char *const kEmbeddedKernelNames[] = {" + ", ".join('"%s"' % os.path.basename(f) for f in files) + ", nullptr};\n")
    o.write("const char *const kEmbeddedKernelBodies[] = {\n" + ",\n".join(lit(open(f).read()) for f in files) + ", nullptr};\n")
    o.write("const int kEmbeddedKernelCount = %d;\n}\n" % len(files))
